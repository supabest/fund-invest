export function extractInd(etfName: string): string {
  let s = etfName;
  for (const p of FUND_PREFIXES) {
    if (s.startsWith(p)) {
      s = s.slice(p.length);
      break;
    }
  }
  return normalizeInd(s.split(/ETF/)[0].replace(/[A-Za-z0-9·\-—]/g, "")) || s;
}
export function normalizeInd(raw: string): string {
  return MERGE[raw] ?? raw;
}

