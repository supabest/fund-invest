/** 原板块名 → 同花顺 L2（或 FOOD_L1）；未收录或已剔除 → null。 */
export function toL2(canonical: string): string | null {
  if (!(canonical in IND_TO_L2)) return null;
  const v = IND_TO_L2[canonical];
  return v === null ? null : v;
}

/** true = 该板块明确剔除（在表中且为 null），区别于「表里根本没这条」的未命中。 */
export function isDropped(canonical: string): boolean {
  return canonical in IND_TO_L2 && IND_TO_L2[canonical] === null;
}

/**
 * 表里没收录的板块名 —— 宇宙重建后新冒出的名字。沿用「宁缺毋滥」纪律：
 * 只报警、不入池，绝不让剥字名重新变成正式行业名。
 */
export function unmappedCanonical(inds: string[]): string[] {
  return inds.filter((i) => !(i in IND_TO_L2));
}

/** 构建期自检：映射目标必须是合法 L2/FOOD_L1，否则抛错（防手滑写错行业名）。 */
export function assertTargets(map: Record<string, string | null> = IND_TO_L2): string[] {
  const bad = Object.entries(map)
    .filter(([, v]) => v !== null && !L2_TARGETS.has(v))
    .map(([k, v]) => `${k} -> ${v}`);
  if (bad.length) {
    throw new Error(`IND_TO_L2 存在非法行业名（不在同花顺 L2 中）: ${bad.join(", ")}`);
  }
  return bad;
}
